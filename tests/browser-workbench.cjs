/** Run a test-only API+Worker at BASE_URL (default :8030), then node tests/browser-workbench.cjs. */
const { chromium, expect } = require('../apps/web/node_modules/@playwright/test');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const base = process.env.BASE_URL || 'http://127.0.0.1:8030';
  const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const context = await browser.newContext({viewport:{width:1600,height:1100},acceptDownloads:true});
  const page = await context.newPage(), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const folder=path.resolve('tmp/workbench-screenshots');fs.mkdirSync(folder,{recursive:true});
  try {
    const created=await context.request.post(`${base}/api/experiments`,{data:{goal:{name:`3D 工作台验收 ${Date.now()}`,budget:{max_generations:3,batch_size:8,max_l1_evals:100,max_l2_evals:100}},seed:42,evaluation_mode:'demo',optimizer:'random'}});
    expect(created.status()).toBe(201);const initial=await created.json();
    await expect.poll(async()=> (await (await context.request.get(`${base}/api/experiments/${initial.id}`)).json()).status,{timeout:40000}).toBe('COMPLETED');
    const original=await (await context.request.get(`${base}/api/experiments/${initial.id}`)).json();
    expect(original.pareto_ids.length).toBeGreaterThan(1);
    await page.goto(base);
    await expect(page.locator('.experiment-title h2')).toHaveText(original.name);
    await expect(page.locator('.drone-canvas canvas')).toHaveCount(1,{timeout:20000});
    await expect(page.locator('[data-webgl=unavailable]')).toHaveCount(0);
    const selected=original.candidates.find(c=>c.status==='PASSED');
    const convergence=page.locator(`[data-chart=convergence] [data-candidate-id="${selected.candidate_id}"]`);
    const pareto=page.locator(`[data-chart=pareto] [data-candidate-id="${selected.candidate_id}"]`);
    await convergence.focus();await expect(pareto).toHaveAttribute('data-hovered','true');
    await convergence.press('Enter');
    await expect(page.getByRole('dialog')).toContainText(`候选 ${selected.proposal_index+1}`);
    await page.getByRole('button',{name:'关闭详情'}).click();
    await expect(convergence).toHaveAttribute('data-selected','true');await expect(pareto).toHaveAttribute('data-selected','true');
    await expect(page.locator('#candidate-studio')).toHaveAttribute('data-selected-candidate',selected.candidate_id);
    await page.getByRole('button',{name:'放大收敛图'}).click();
    await page.getByRole('slider',{name:'收敛图水平位置'}).fill('0.6');
    await page.getByRole('button',{name:'重置收敛图'}).click();
    await page.getByRole('button',{name:'查看帕累托方案'}).click();
    const drawer=page.getByRole('dialog',{name:'帕累托方案对比'});
    await expect(drawer).toBeVisible();
    const front=original.candidates.filter(c=>original.pareto_ids.includes(c.candidate_id));
    await drawer.getByRole('checkbox',{name:`对比候选 ${front[0].proposal_index+1}`,exact:true}).check();
    await drawer.getByRole('checkbox',{name:`对比候选 ${front[1].proposal_index+1}`,exact:true}).check();
    await drawer.getByRole('button',{name:/参数对比/}).click();
    await expect(drawer.locator('.diff-row').first()).toBeVisible();
    await page.screenshot({path:path.join(folder,'pareto-comparison.png')});
    await drawer.getByRole('button',{name:'在候选列表中仅看帕累托方案'}).click();
    await expect(page.locator('.results-panel tbody tr')).toHaveCount(front.length);
    await page.getByRole('button',{name:'全部候选',exact:true}).click();
    await page.getByRole('button',{name:'进入参数修订',exact:true}).click();
    const studio=page.getByRole('dialog',{name:'3D 参数修订工作台'});
    await expect(studio).toBeVisible();await expect(studio.locator('canvas')).toHaveCount(1);
    await studio.getByRole('button',{name:'俯视 FRD',exact:true}).click();
    await studio.getByRole('button',{name:'侧视',exact:true}).click();
    await studio.getByRole('button',{name:'等轴测',exact:true}).click();
    await page.waitForTimeout(350);
    const assembled=await studio.locator('canvas').screenshot();
    await studio.getByRole('slider',{name:'拆解比例',exact:true}).fill('1');
    await page.waitForTimeout(500);
    const exploded=await studio.locator('canvas').screenshot();
    expect(assembled.equals(exploded)).toBe(false);
    await page.screenshot({path:path.join(folder,'studio-exploded.png')});
    await studio.getByRole('button',{name:'桨叶旋转',exact:true}).click();
    await expect(studio.getByRole('button',{name:'停止桨叶',exact:true})).toHaveAttribute('aria-pressed','true');
    await studio.getByRole('button',{name:'停止桨叶',exact:true}).click();
    await studio.getByRole('slider',{name:'拆解比例',exact:true}).fill('0');
    await page.waitForTimeout(450);
    const bounds=await studio.locator('canvas').boundingBox();
    await studio.locator('canvas').click({position:{x:bounds.width/2,y:bounds.height/2}});
    await expect(studio.locator('.part-selectors button[aria-pressed=true]')).toHaveCount(1);
    await studio.locator('.part-selectors').getByRole('button',{name:'电池',exact:true}).click();
    await expect(studio.locator('#editor-power')).toHaveClass(/active-editor/);
    const capacity=studio.getByLabel('电池容量 / Wh',{exact:true});
    const oldCapacity=+await capacity.inputValue();const newCapacity=oldCapacity-5;
    await capacity.fill(String(newCapacity));
    await page.waitForTimeout(1200); // API polling must not reset the revision draft.
    await expect(capacity).toHaveValue(String(newCapacity));
    await studio.getByRole('button',{name:'重置修改',exact:true}).click();
    await expect(capacity).toHaveValue(String(oldCapacity));
    await expect(studio.getByRole('button',{name:'保存并运行单次评估'})).toBeDisabled();
    await studio.getByRole('button',{name:'对称快捷',exact:true}).click();
    await studio.getByLabel('桨半径 / m',{exact:true}).fill('0.4');
    await expect(studio.locator('.studio-live')).toContainText('桨盘干涉');
    await page.screenshot({path:path.join(folder,'interference.png')});
    await studio.getByLabel('桨半径 / m',{exact:true}).fill(String(selected.ir.rotors[0].prop_radius_m));
    await capacity.fill(String(newCapacity));
    const downloading=page.waitForEvent('download');
    await studio.getByRole('button',{name:'导出修订版 DroneIR'}).click();
    const draftPath=path.join(folder,'revised-drone.json');await (await downloading).saveAs(draftPath);
    expect(JSON.parse(fs.readFileSync(draftPath,'utf8')).power.capacity_wh).toBe(newCapacity);
    const saving=page.waitForResponse(r=>r.url().endsWith('/candidates/evaluate')&&r.request().method()==='POST');
    await studio.getByRole('button',{name:'保存并运行单次评估'}).click();
    const response=await saving;expect(response.status()).toBe(202);const revision=await response.json();
    expect(revision.parent_ir_hash).toBe(selected.ir_hash);expect(revision.source).toBe('manual_revision');
    await expect(studio).toHaveCount(0);
    await expect.poll(async()=> (await (await context.request.get(`${base}/api/experiments/${initial.id}/candidates/${revision.candidate_id}`)).json()).candidate.status,{timeout:20000}).toBe('PASSED');
    await expect(page.locator(`[data-chart=convergence] [data-candidate-id="${revision.candidate_id}"]`)).toHaveAttribute('data-selected','true');
    await expect(page.locator(`[data-chart=pareto] [data-candidate-id="${revision.candidate_id}"]`)).toHaveAttribute('data-selected','true');
    const after=await (await context.request.get(`${base}/api/experiments/${initial.id}`)).json();
    const revisionDetails=await (await context.request.get(`${base}/api/experiments/${initial.id}/candidates/${revision.candidate_id}`)).json();
    expect(Number.isFinite(revisionDetails.evaluations.at(-1).result.fitness_score)).toBe(true);
    expect(after.candidates.slice(0,24)).toEqual(original.candidates);expect(after.status).toBe('COMPLETED');
    await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:path.join(folder,'desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});await page.evaluate(()=>window.scrollTo(0,0));
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:path.join(folder,'mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'进入参数修订',exact:true}).click();
    await expect(studio.locator('canvas')).toHaveCount(1);
    const mobileCapacity=studio.getByLabel('电池容量 / Wh',{exact:true});
    await mobileCapacity.fill(String(newCapacity-1));
    page.once('dialog',d=>d.dismiss());await studio.getByRole('button',{name:'关闭 3D 工作台'}).click();
    await expect(studio).toBeVisible();
    await page.screenshot({path:path.join(folder,'mobile-studio.png')});
    page.once('dialog',d=>d.accept());await studio.getByRole('button',{name:'关闭 3D 工作台'}).click();
    await expect(studio).toHaveCount(0);
    expect(errors).toEqual([]);
    console.log(JSON.stringify({passed:true,candidates:original.candidates.length,pareto:front.length,revision:revision.candidate_id,webgl:true,screenshots:folder}));
  } catch(e) {
    console.error('Browser errors:',errors);await page.screenshot({path:path.join(folder,'failure.png'),fullPage:true}).catch(()=>{});throw e;
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
