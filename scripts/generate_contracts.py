"""Generate JSON Schema and TypeScript from the authoritative Pydantic contracts."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps/backend"))
from drone_lab.domain import (  # noqa: E402
    CachePruneRequest, CachePruneResult, CandidateDetails, DesignGoal, DroneIR, EvalResult, ExperimentRequest,
    ExperimentRun, HealthStatus, L1CheckRequest, PresetSpec, RenameRunRequest, RevisionRequest,
    RunSummary, TestScenario, baseline_ir,
)


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "string":
        return "string"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts_type(v) for v in schema["prefixItems"]) + "]"
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        if "properties" not in schema:
            additional = schema.get("additionalProperties", {})
            return f"Record<string, {ts_type(additional) if isinstance(additional, dict) else 'unknown'}>"
        required = set(schema.get("required", []))
        return "{\n" + "\n".join(f"  {json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};" for name, value in schema["properties"].items()) + "\n}"
    raise ValueError(f"Unsupported schema: {schema}")


def main():
    definitions = {}
    folder = ROOT/"schemas"
    folder.mkdir(exist_ok=True)
    models = (
        DesignGoal, DroneIR, TestScenario, EvalResult, ExperimentRequest, ExperimentRun, RunSummary, CandidateDetails,
        RevisionRequest, CachePruneRequest, CachePruneResult, HealthStatus, L1CheckRequest, PresetSpec, RenameRunRequest,
    )
    for model in models:
        schema = model.model_json_schema(mode="serialization")
        (folder/f"{model.__name__}.schema.json").write_text(json.dumps(schema, indent=2, ensure_ascii=False)+"\n", encoding="utf-8")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    output = "// Generated by scripts/generate_contracts.py. Do not edit by hand.\n\n"
    output += "\n\n".join(f"export type {name} = {ts_type(schema)};" for name, schema in sorted(definitions.items())) + "\n"
    (ROOT/"apps/web/src/contracts.ts").write_text(output, encoding="utf-8")
    examples = ROOT/"examples"
    examples.mkdir(exist_ok=True)
    for name, model in [("quadrotor", baseline_ir()), ("hover-scenario", TestScenario()), ("experiment", ExperimentRequest())]:
        (examples/f"{name}.json").write_text(model.model_dump_json(indent=2)+"\n", encoding="utf-8")
    print(f"Generated {len(models)} JSON Schemas, frontend contracts and examples")


if __name__ == "__main__":
    main()
